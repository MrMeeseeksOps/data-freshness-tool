CREATE OR REPLACE VIEW DATA_OBSERVABILITY.REPORTING.V_FRESHNESS_HISTORY AS
SELECT * FROM DATA_OBSERVABILITY.AUDIT.FRESHNESS_RESULTS;

CREATE OR REPLACE VIEW DATA_OBSERVABILITY.REPORTING.V_CURRENT_FRESHNESS AS
WITH latest AS (
 SELECT * FROM DATA_OBSERVABILITY.AUDIT.FRESHNESS_RESULTS
 QUALIFY ROW_NUMBER() OVER (PARTITION BY MONITOR_ID ORDER BY CHECKED_AT DESC, RESULT_ID DESC)=1
)
SELECT m.*, r.CHECKED_AT, r.LATEST_DATA_AT, r.LAG_SECONDS, r.QUERY_DURATION_MS,
 r.SNOWFLAKE_QUERY_ID, r.ERROR_MESSAGE,
 CASE WHEN r.CHECKED_AT IS NULL OR
 DATEDIFF('second',r.CHECKED_AT,CURRENT_TIMESTAMP()) > m.CHECK_INTERVAL_MINUTES*60+900
 THEN 'MISSING' ELSE r.STATUS END AS STATUS
FROM DATA_OBSERVABILITY.CONFIG.FRESHNESS_MONITORS m
LEFT JOIN latest r ON m.MONITOR_ID=r.MONITOR_ID;

CREATE OR REPLACE VIEW DATA_OBSERVABILITY.REPORTING.V_FRESHNESS_SUMMARY AS
SELECT OWNER_TEAM, STATUS, COUNT(*) AS MONITOR_COUNT
FROM DATA_OBSERVABILITY.REPORTING.V_CURRENT_FRESHNESS WHERE ENABLED
GROUP BY OWNER_TEAM, STATUS;
