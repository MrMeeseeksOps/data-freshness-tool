CREATE TABLE IF NOT EXISTS DATA_OBSERVABILITY.AUDIT.MONITOR_RUNS (
 RUN_ID VARCHAR NOT NULL, STARTED_AT TIMESTAMP_TZ NOT NULL, COMPLETED_AT TIMESTAMP_TZ,
 STATUS VARCHAR NOT NULL, MONITORS_EVALUATED INTEGER, MONITORS_FAILED INTEGER,
 ERROR_MESSAGE VARCHAR, PRIMARY KEY (RUN_ID)
);
CREATE TABLE IF NOT EXISTS DATA_OBSERVABILITY.AUDIT.FRESHNESS_RESULTS (
 RESULT_ID VARCHAR NOT NULL, RUN_ID VARCHAR NOT NULL, MONITOR_ID NUMBER NOT NULL,
 CHECKED_AT TIMESTAMP_TZ NOT NULL, LATEST_DATA_AT TIMESTAMP_TZ, LAG_SECONDS FLOAT,
 STATUS VARCHAR NOT NULL, QUERY_DURATION_MS FLOAT, SNOWFLAKE_QUERY_ID VARCHAR,
 ERROR_MESSAGE VARCHAR, PRIMARY KEY (RUN_ID, MONITOR_ID)
);
