-- Execute role DDL/grants as SECURITYADMIN; object grants require ownership or MANAGE GRANTS.
CREATE ROLE IF NOT EXISTS FRESHNESS_CONFIG_READ;
CREATE ROLE IF NOT EXISTS FRESHNESS_AUDIT_WRITE;
CREATE ROLE IF NOT EXISTS FRESHNESS_SOURCE_READ;
CREATE ROLE IF NOT EXISTS FRESHNESS_RUNTIME;
GRANT ROLE FRESHNESS_CONFIG_READ TO ROLE FRESHNESS_RUNTIME;
GRANT ROLE FRESHNESS_AUDIT_WRITE TO ROLE FRESHNESS_RUNTIME;
GRANT ROLE FRESHNESS_SOURCE_READ TO ROLE FRESHNESS_RUNTIME;
GRANT USAGE ON DATABASE DATA_OBSERVABILITY TO ROLE FRESHNESS_CONFIG_READ;
GRANT USAGE ON SCHEMA DATA_OBSERVABILITY.CONFIG TO ROLE FRESHNESS_CONFIG_READ;
GRANT SELECT ON TABLE DATA_OBSERVABILITY.CONFIG.FRESHNESS_MONITORS TO ROLE FRESHNESS_CONFIG_READ;
GRANT USAGE ON SCHEMA DATA_OBSERVABILITY.REPORTING TO ROLE FRESHNESS_CONFIG_READ;
GRANT SELECT ON ALL VIEWS IN SCHEMA DATA_OBSERVABILITY.REPORTING TO ROLE FRESHNESS_CONFIG_READ;
GRANT USAGE ON DATABASE DATA_OBSERVABILITY TO ROLE FRESHNESS_AUDIT_WRITE;
GRANT USAGE ON SCHEMA DATA_OBSERVABILITY.AUDIT TO ROLE FRESHNESS_AUDIT_WRITE;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA DATA_OBSERVABILITY.AUDIT
 TO ROLE FRESHNESS_AUDIT_WRITE;
-- Administrator must explicitly grant USAGE on the monitoring warehouse and each
-- source database/schema, and SELECT on individual source tables to FRESHNESS_SOURCE_READ.
-- Never grant source INSERT/UPDATE/DELETE/OWNERSHIP. Assign FRESHNESS_RUNTIME to the service user.
