CREATE TABLE IF NOT EXISTS DATA_OBSERVABILITY.CONFIG.FRESHNESS_MONITORS (
 MONITOR_ID NUMBER NOT NULL,
 DATABASE_NAME VARCHAR NOT NULL,
 SCHEMA_NAME VARCHAR NOT NULL,
 TABLE_NAME VARCHAR NOT NULL,
 TIMESTAMP_COLUMN VARCHAR NOT NULL,
 CADENCE_TYPE VARCHAR DEFAULT 'CUSTOM',
 WARNING_THRESHOLD_MINUTES FLOAT NOT NULL,
 CRITICAL_THRESHOLD_MINUTES FLOAT NOT NULL,
 CHECK_INTERVAL_MINUTES INTEGER DEFAULT 15,
 ENABLED BOOLEAN DEFAULT TRUE,
 OWNER_TEAM VARCHAR DEFAULT 'unknown',
 LAST_MODIFIED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
 STRATEGY VARCHAR DEFAULT 'MAX_TIMESTAMP',
 TIME_ZONE VARCHAR DEFAULT 'UTC',
 EXPECTED_ARRIVAL VARCHAR,
 PRIMARY KEY (MONITOR_ID)
);
-- EXPECTED_ARRIVAL reserves a JSON rule for business days/monthly deadlines.
-- Runtime rejects populated rules until an EXPECTED_ARRIVAL strategy is implemented.
-- Standard-table primary keys are informational. Single-writer metadata administration
-- and duplicate detection at runtime are mandatory; use MERGE by MONITOR_ID.
